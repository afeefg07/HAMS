// ==========================================
// Dropdown Elements
// ==========================================

const block = document.getElementById("block");
const section = document.getElementById("section");
const locationSelect = document.getElementById("location");
const subLocation = document.getElementById("subLocation");

// ==========================================
// Block Changed
// ==========================================

block.addEventListener("change", function () {

    section.innerHTML = '<option value="">Select Section</option>';
    locationSelect.innerHTML = '<option value="">Select Location</option>';
    subLocation.innerHTML = '<option value="">Select Sub Location</option>';

    if (!hospitalData[this.value]) return;

    Object.keys(hospitalData[this.value]).forEach(function (sec) {

        section.innerHTML += `<option value="${sec}">${sec}</option>`;

    });

});

// ==========================================
// Section Changed
// ==========================================

section.addEventListener("change", function () {

    locationSelect.innerHTML = '<option value="">Select Location</option>';
    subLocation.innerHTML = '<option value="">Select Sub Location</option>';

    if (!hospitalData[block.value]) return;

    const data = hospitalData[block.value][this.value];

    if (!data) return;

    Object.keys(data).forEach(function (loc) {

        locationSelect.innerHTML += `<option value="${loc}">${loc}</option>`;

    });

});

// ==========================================
// Location Changed
// ==========================================

locationSelect.addEventListener("change", function () {

    subLocation.innerHTML = '<option value="">Select Sub Location</option>';

    if (!hospitalData[block.value]) return;
    if (!hospitalData[block.value][section.value]) return;

    const rooms = hospitalData[block.value][section.value][this.value];

    if (!rooms) return;

    rooms.forEach(function (room) {

        subLocation.innerHTML += `<option value="${room}">${room}</option>`;

    });

});